`timescale 10ns / 1ps

module tb();
    reg clk;
    reg rst;
    reg signed [15:0] tb_A;
    reg signed [15:0] tb_B; //коефіцієнт фільтра
    
    wire signed [31:0] tb_P;

    // Підключаємо top модуль
    top dut (
        .clk(clk),
        .rst(rst),
        .in_sample_A(tb_A),
        .in_coeff_B(tb_B),
        .out_mac_P(tb_P)
    );

    // Генератор тактової частоти 100 МГц (період 10 нс)
    always begin
        #5 clk = ~clk;
    end

    initial begin
        // 1. Початкове скидання (очищення акумулятора)
        clk = 0;
        rst = 1;
        tb_A = 0; 
        
        // ЖОРСТКО ФІКСУЄМО КОЕФІЦІЄНТ ФІЛЬТРА
        // Нехай коефіцієнт фільтра h[n] дорівнює 5
        tb_B = 16'd5; 
        #20;
        
        rst = 0; // Знімаємо скидання
        #10;

        // --- ПОДАЧА ПОСЛІДОВНОСТІ ВХІДНИХ ВІДЛІКІВ (Сигнал змінюється) ---
        
        // Такт 1: Прийшов відлік x[0] = 2.
        // Очікуємо в акумуляторі: 2 * 5 = 10
        tb_A = 16'd2;   
        #10;
        
        // Такт 2: Прийшов наступний відлік x[1] = 3.
        // Очікуємо в акумуляторі: 10 + (3 * 5) = 25
        tb_A = 16'd3;   
        #10;
        
        // Такт 3: Прийшов відлік x[2] = -1.
        // Очікуємо в акумуляторі: 25 + (-1 * 5) = 20
        tb_A = -16'd1;  
        #10;

        // Зупиняємо подачу сигналу (сигнал затих / став 0)
        tb_A = 0;

        // Чекаємо, поки конвеєр виштовхне всі результати на вихід P
        #60;
        
        $display("Симуляція завершена.");
        $finish;
    end

endmodule 