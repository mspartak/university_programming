`timescale 1ns / 1ps

module tb;

    // Вхідні сигнали для тестування (керуються з тестбенчу)
    reg clk;
    reg reset;
    reg in;

    // Вихідний сигнал з модуля
    wire out;

    // Підключення вашого модуля (Instance)
    seq_det_101_moore uut (
        .clk(clk),
        .reset(reset),
        .in(in),
        .out(out)
    );

    // ГЕНЕРАЦІЯ СИГНАЛУ СИНХРОНІЗАЦІЇ (CLK): період 10 нс (100 МГц)
    always begin
        #5 clk = ~clk;
    end

    // ГОЛОВНИЙ БЛОК ТЕСТУВАННЯ
    initial begin
        // Ініціалізація початкових значень
        clk = 0;
        reset = 1;
        in = 0;

        // Тримаємо скидання (reset) протягом 2 тактів
        #20;
        reset = 0;
        #10; // Чекаємо ще такт для стабілізації системи

        // --- ЕТАП 1: ПЕРЕВІРКА НЕПРАВИЛЬНИХ ПОСЛІДОВНОСТЕЙ ---
        
        // Послідовність 1: Багато нулів (0-0-0) -> out має бути 0
        in = 0; #10;
        in = 0; #10;
        in = 0; #10;

        // Послідовність 2: Багато одиниць (1-1-1) -> out має бути 0
        in = 1; #10;
        in = 1; #10;
        in = 1; #10;

        // Послідовність 3: Частковий збіг, але обрив (1-0-0) -> out має бути 0
        in = 1; #10; // перехід в S1
        in = 0; #10; // перехід в S2
        in = 0; #10; // повернення в S0 (скидання прогресу)

        // --- ЕТАП 2: ПЕРЕВІРКА ПРАВИЛЬНОЇ ПОСЛІДОВНОСТІ 101 ---

        // Передаємо першу '1'
        in = 1; #10; // модуль перейде в стан S1

        // Передаємо '0'
        in = 0; #10; // модуль перейде в стан S2

        // Передаємо другу '1' (послідовність завершена!)
        in = 1; #10; // модуль перейде в стан S3. Тут out стане 1.

        // Утримуємо сигнал, щоб побачити вихід на графіку
        in = 0; #10; // модуль повернеться в S2 (оскільки overlapping активний)
        
        // Завершення симуляції
        #40;
        $finish;
    end
      
endmodule
